"""Generate the tabular champion's model card: docs/model_card_tabular.md.

Every number is measured when the card is built, from the served @champion
(registry or bundle, as the batch job loads it) on the untouched test split:
performance at the decision threshold, global feature importance (mean
absolute TreeSHAP contribution, src/explain), the most common top reason
among routed claims, and the fairness audit (src/evaluation/fairness). The
findings section is derived from those numbers too, so the card stays true
when the champion changes. Re-run it after every promotion.

Usage:
    python -m src.evaluation.model_card
"""

from __future__ import annotations

import logging
from typing import Any

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

from src.batch.score import load_champion
from src.common.config import ROOT, load_config, resolve
from src.common.logging import get_logger, log_event
from src.evaluation import fairness
from src.explain import reasons
from src.explain.champion import load_explainer
from src.features.transform import feature_columns
from src.training.onnx_export import onnx_inputs
from src.training.tracking import train_config

logger = get_logger("evaluation.model_card")
CARD = ROOT / "docs" / "model_card_tabular.md"
# A group routed at this multiple of the overall rate (or more) is a finding.
OVER_ROUTED = 1.5


def table(headers: list[str], rows: list[list[Any]]) -> str:
    """A Markdown table with its | characters aligned (repo standard)."""
    cells = [headers] + [[str(c) for c in row] for row in rows]
    widths = [max(len(r[i]) for r in cells) for i in range(len(headers))]

    def line(row: list[str]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(row, widths, strict=True)) + " |"

    rule = "| " + " | ".join("-" * w for w in widths) + " |"
    return "\n".join([line(cells[0]), rule, *(line(r) for r in cells[1:])])


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def direction(calibration: float | None) -> str:
    if calibration is None:
        return "no high-cost claims to compare"
    word = "overstates" if calibration > 1 else "understates"
    return f"the model {word} this group's risk"


def findings(audit: dict[str, Any], top_reasons: pd.Series, routed: int) -> list[str]:
    """Plain statements the numbers support, for the Limitations section."""
    out = []
    overall = audit["overall"]
    if top_reasons.size:
        feature, count = str(top_reasons.index[0]), int(top_reasons.iloc[0])
        out.append(
            f"`{feature}` is the top reason for {count} of {routed} routed claims "
            f"({pct(count / routed)}): routing leans on one feature."
        )
    for attribute, groups in audit["groups"].items():
        for name, g in groups.items():
            if g["flagged_rate"] >= OVER_ROUTED * overall["flagged_rate"]:
                out.append(
                    f"{attribute} {name}: routed at {pct(g['flagged_rate'])} vs "
                    f"{pct(overall['flagged_rate'])} overall, precision {pct(g['precision'])}, "
                    f"calibration {g['calibration']} ({direction(g['calibration'])})."
                )
    widest = max(
        (g for groups in audit["groups"].values() for g in groups.values() if g["judged"]),
        key=lambda g: g["recall_interval"][1] - g["recall_interval"][0],
    )
    lo, hi = widest["recall_interval"]
    out.append(
        f"The fairness check has little power: {overall['positives']} high-cost test claims, "
        f"and recall intervals as wide as {pct(lo)} to {pct(hi)}. No alert is not proof of "
        "equal treatment."
    )
    return out


def render(info: dict[str, Any]) -> str:
    m, perf, audit = info["model"], info["performance"], info["audit"]
    imp = info["importance"]
    params = ", ".join(
        f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}"
        for k, v in sorted(m["params"].items())
    )
    group_rows = [
        [
            attribute.replace("_", " "),
            name,
            f"{g['rows']:,}",
            g["positives"],
            pct(g["recall"]),
            f"{pct(g['recall_interval'][0])} to {pct(g['recall_interval'][1])}",
            pct(g["flagged_rate"]),
            pct(g["precision"]),
            g["calibration"],
            "yes" if g["judged"] else "no (too few)",
        ]
        for attribute, groups in audit["groups"].items()
        for name, g in groups.items()
    ]
    sections = [
        f"# Model card: {m['name']} v{m['version']}",
        "Generated by `make model-card` from the served champion; every number is measured "
        "on the untouched test split. Do not edit by hand: re-run it after a promotion.",
        "## Intended use",
        "- **Task:** predict whether a new motor claim will cost more than "
        f"€{info['high_cost_threshold']:,} and route it to a senior adjuster when the "
        f"probability is at least the decision threshold ({m['threshold']}).\n"
        "- **Users:** claims handlers triaging new claims. Each routed claim comes with reason "
        "codes (below).\n"
        "- **Not for:** pricing, accepting or denying a claim, or judging the person who "
        "claims. Routing only decides who looks at the claim first.",
        "## Model",
        table(
            ["Item", "Value"],
            [
                ["Algorithm", "LightGBM, served as ONNX"],
                ["Training run", f"`{m['run_id']}`"],
                ["Hyperparameters", params],
                ["Monotone rules", m["monotone"] or "none"],
                ["Features", ", ".join(info["features"])],
                ["Decision threshold", f"{m['threshold']} (best F1 on validation)"],
            ],
        ),
        "## Data",
        "freMTPL2 (French motor third-party liability, OpenML 41214 and 41215): real policies "
        "and claim amounts. Split 70/15/15 by policy, so no policy is in two splits, and "
        "stratified on the target. The adjuster notes are synthetic and not used by this "
        "model.",
        "## Performance (test split)",
        table(
            ["Metric", "Value"],
            [
                ["Claims", f"{perf['rows']:,}"],
                ["High-cost rate", pct(perf["positive_rate"])],
                ["PR-AUC", f"{perf['pr_auc']:.4f} ({perf['lift']:.2f}x the high-cost rate)"],
                ["ROC-AUC", f"{perf['roc_auc']:.4f}"],
                ["Routed to a senior adjuster", pct(audit["overall"]["flagged_rate"])],
                ["Recall (high-cost claims routed)", pct(audit["overall"]["recall"])],
                [
                    "Precision (routed claims that were high-cost)",
                    pct(audit["overall"]["precision"]),
                ],
                ["Calibration (mean probability / actual rate)", audit["overall"]["calibration"]],
            ],
        ),
        "## Explainability",
        "Reason codes come from TreeSHAP, built into LightGBM: each claim's score splits "
        "exactly into one contribution per feature. The served model is ONNX, so it is "
        "rebuilt as LightGBM from its training recipe, and every explanation first checks that "
        f"the rebuild predicts the same (largest difference here: {info['parity']:.1e}). The "
        f"nightly batch job stores up to {info['top_k']} reasons per claim in its `reasons` table.",
        "Global importance, mean absolute contribution (log-odds) over the test claims:",
        table(
            ["Feature", "Mean abs. contribution", "Top reason for routed claims"],
            [
                [
                    reasons.DISPLAY.get(f, f),
                    f"{v:.3f}",
                    int(info["top_reasons"].get(reasons.DISPLAY.get(f, f), 0)),
                ]
                for f, v in imp.items()
            ],
        ),
        "## Fairness",
        "Does routing treat groups alike? The judged rule is equal opportunity: a group is "
        "flagged when its recall's "
        f"{int(100 * audit['confidence'])}% interval lies entirely below the overall recall "
        f"({pct(audit['overall']['recall'])}). Driver age and region are standard motor rating "
        "factors; this checks the routing outcome, not whether a factor may be used. freMTPL2 "
        "has no gender or other protected attributes.",
        f"**Alerts:** {'; '.join(audit['alerts']) if audit['alerts'] else 'none'}.",
        table(
            [
                "Attribute",
                "Group",
                "Claims",
                "High-cost",
                "Recall",
                "Recall interval",
                "Routed",
                "Precision",
                "Calibration",
                "Judged",
            ],
            group_rows,
        ),
        "## Limitations",
        "\n".join(f"- {line}" for line in info["findings"])
        + "\n- Reason codes explain the model, not the world: a feature raising the score is "
        "not evidence that it causes costly claims.\n"
        "- The rebuild depends on the training data version (DVC). If the data changes, the "
        "parity check fails and no reasons are produced, by design.",
        "## Monitoring",
        "- Feature drift on API requests (`make drift`) and delayed-label performance in the "
        "nightly batch (`make batch-backfill`); either can trigger a retrain through Dagster.\n"
        "- Re-run `make fairness` and `make model-card` after every promotion.",
    ]
    return "\n\n".join(sections) + "\n"


def collect() -> dict[str, Any]:
    data_cfg, cfg = load_config(), train_config()
    test = pd.read_parquet(resolve(data_cfg["paths"]["processed_dir"]) / "test.parquet")
    model = load_champion()
    explainer = load_explainer(model.session)
    probabilities = model.session.run(None, onnx_inputs(test, data_cfg))[1][:, 1]
    parity = float(np.max(np.abs(probabilities - explainer.pipeline.predict_proba(test)[:, 1])))
    labels = test["is_high_cost"].to_numpy(dtype=bool)

    contrib = reasons.contributions(explainer.pipeline, test)
    codes = reasons.reason_codes(
        test, contrib, int(cfg["explain"]["top_k"]), float(cfg["explain"]["min_contribution"])
    )
    routed = test.loc[probabilities >= model.threshold, "claim_id"]
    top = codes[codes["claim_id"].isin(routed) & (codes["rank"] == 1)]["feature"].value_counts()
    audit = fairness.audit(test, probabilities, model.threshold, cfg["fairness"])
    pr_auc = float(average_precision_score(labels, probabilities))
    return {
        "model": {
            "name": model.name,
            "version": model.version,
            "threshold": model.threshold,
            "run_id": explainer.recipe.run_id,
            "params": explainer.recipe.params,
            "monotone": explainer.recipe.monotone,
        },
        "features": feature_columns(data_cfg),
        "high_cost_threshold": int(data_cfg["targets"]["high_cost_threshold"]),
        "performance": {
            "rows": len(test),
            "positive_rate": float(labels.mean()),
            "pr_auc": pr_auc,
            "lift": pr_auc / float(labels.mean()),
            "roc_auc": float(roc_auc_score(labels, probabilities)),
        },
        "parity": parity,
        "top_k": int(cfg["explain"]["top_k"]),
        "importance": reasons.importance(contrib),
        "top_reasons": top,
        "audit": audit,
        "findings": findings(audit, top, len(routed)),
    }


def run() -> int:
    info = collect()
    CARD.parent.mkdir(parents=True, exist_ok=True)
    CARD.write_text(render(info))
    log_event(
        logger,
        logging.INFO,
        "model_card_written",
        model=f"{info['model']['name']} v{info['model']['version']}",
        card=str(CARD.relative_to(ROOT)),
        findings=len(info["findings"]),
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(run())
